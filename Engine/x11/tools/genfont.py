#!/usr/bin/env python3
"""Generates font6x13.h from the X.Org misc-fixed 6x13 font (public domain),
used for core-protocol text (xterm and other Xlib programs).
  python3 genfont.py /usr/share/fonts/X11/misc/6x13-ISO8859-1.pcf.gz > ../font6x13.h
"""
import gzip, io, sys
from PIL import PcfFontFile

data = gzip.open(sys.argv[1]).read()
pcf = PcfFontFile.PcfFontFile(io.BytesIO(data))
W, H, ASCENT = 6, 13, 11
rows = []
for code in range(256):
    g = pcf.glyph[code]
    bits = [0] * H
    if g:
        (dx, dy), (x0, y0, x1, y1), (_a, _b, _c, _d), im = g
        # bbox is relative to the origin on the baseline, y down.
        for y in range(im.size[1]):
            for x in range(im.size[0]):
                if im.getpixel((x, y)):
                    px = x0 + x
                    py = y0 + ASCENT + y
                    if 0 <= px < W and 0 <= py < H:
                        bits[py] |= 0x80 >> px
    rows.append(bits)
print("/* X.Org misc-fixed 6x13 (ISO8859-1), public domain. Generated by tools/genfont.py. */")
print("#define FONT_W %d\n#define FONT_H %d\n#define FONT_ASCENT %d\n#define FONT_DESCENT %d" % (W, H, ASCENT, H - ASCENT))
print("static const unsigned char kFont6x13[256][%d] = {" % H)
for code, bits in enumerate(rows):
    print("  {%s}, /* %d */" % (",".join("0x%02x" % b for b in bits), code))
print("};")
